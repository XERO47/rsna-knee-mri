# -*- coding: utf-8 -*-
"""Generate and push a per-stage extraction kernel from the single source file.

Kaggle script kernels take one code file and no environment variables, and the stage / pass /
model are environment-driven. Copying extract_labels.py per stage would fork the prompt, which is
the one thing that must stay identical across every report and every pass -- so the copy is
GENERATED here, from the committed source, with nothing but an env preamble prepended. The
generated directories are gitignored; extract_labels.py stays the only place the prompt lives.

    python push_stage.py pilot N1 Qwen/Qwen2.5-14B-Instruct
    python push_stage.py pilot N2 google/gemma-3-12b-it --rev <sha>
"""
import argparse
import hashlib
import io
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "extract_labels.py"

ap = argparse.ArgumentParser()
ap.add_argument("stage", choices=["probe", "pilot", "full"])
ap.add_argument("pass_name", nargs="?", default="N1")
ap.add_argument("model", nargs="?", default="Qwen/Qwen2.5-14B-Instruct")
ap.add_argument("--rev", default="main", help="pinned HF revision -- 'main' is not reproducible")
ap.add_argument("--quant", default="nf4", choices=["nf4", "awq", "none"])
ap.add_argument("--batch", type=int, default=8, help="reports per forward pass")
ap.add_argument("--shards", type=int, default=1,
                help="workers, one per GPU; >1 spawns a subprocess per GPU and merges")
ap.add_argument("--max-new", type=int, default=1400)
ap.add_argument("--n-probe", type=int, default=10, help="reports in the probe stage")
ap.add_argument("--slug", default=None, help="override the kernel slug")
# vLLM owns both GPUs via tensor parallelism and does its own continuous batching, so it wants
# --shards 1 and a large --batch. bitsandbytes NF4 measured 8 tok/s per worker; vLLM on the same
# cards is reported in the thousands, which is the difference between 93 hours and 3.
ap.add_argument("--engine", default="hf", choices=["hf", "vllm"])
ap.add_argument("--tp", type=int, default=2, help="vLLM tensor-parallel size")
ap.add_argument("--gpu-util", type=float, default=0.90)
ap.add_argument("--max-len", type=int, default=4096)
ap.add_argument("--langs", default="", help="comma-separated language families to keep (empty = all)")
ap.add_argument("--cap", type=int, default=0, help="max studies per language, SEED-sampled (0 = no cap)")
ap.add_argument("--prompt-variant", default="canonical", choices=["canonical", "reworded"],
                help="'reworded' = N2-fallback independently-phrased prompt (same schema)")
ap.add_argument("--datasets", nargs="*", default=["zeroday19/rsna-knee-report-language"])
ap.add_argument("--dry-run", action="store_true")
a = ap.parse_args()

slug = a.slug or (f"rsna-knee-extract-{a.stage}"
                  + ("" if a.pass_name == "N1" else f"-{a.pass_name.lower()}"))
out = HERE.parent / slug.replace("rsna-knee-", "")
out.mkdir(parents=True, exist_ok=True)

src = io.open(SRC, encoding="utf-8").read()
preamble = (
    "# GENERATED by kaggle/extract/push_stage.py -- do not edit. Edit extract_labels.py.\n"
    "import os\n"
    f"os.environ.setdefault('EXTRACT_STAGE', {a.stage!r})\n"
    f"os.environ.setdefault('EXTRACT_PASS', {a.pass_name!r})\n"
    f"os.environ.setdefault('EXTRACT_MODEL', {a.model!r})\n"
    f"os.environ.setdefault('EXTRACT_REV', {a.rev!r})\n"
    f"os.environ.setdefault('EXTRACT_QUANT', {a.quant!r})\n"
    f"os.environ.setdefault('EXTRACT_BATCH', {str(a.batch)!r})\n"
    f"os.environ.setdefault('EXTRACT_N_SHARD', {str(a.shards)!r})\n"
    f"os.environ.setdefault('EXTRACT_MAX_NEW', {str(a.max_new)!r})\n"
    f"os.environ.setdefault('EXTRACT_N_PROBE', {str(a.n_probe)!r})\n"
    f"os.environ.setdefault('EXTRACT_ENGINE', {a.engine!r})\n"
    f"os.environ.setdefault('EXTRACT_TP', {str(a.tp)!r})\n"
    f"os.environ.setdefault('EXTRACT_GPU_UTIL', {str(a.gpu_util)!r})\n"
    f"os.environ.setdefault('EXTRACT_MAX_LEN', {str(a.max_len)!r})\n"
    f"os.environ.setdefault('EXTRACT_LANGS', {a.langs!r})\n"
    f"os.environ.setdefault('EXTRACT_CAP', {str(a.cap)!r})\n"
    f"os.environ.setdefault('EXTRACT_PROMPT_VARIANT', {a.prompt_variant!r})\n"
    f"# source sha256 {hashlib.sha256(src.encode()).hexdigest()[:16]}\n\n")
io.open(out / "extract_labels.py", "w", encoding="utf-8", newline="\n").write(preamble + src)

json.dump({"id": f"zeroday19/{slug}", "title": slug, "code_file": "extract_labels.py",
           "language": "python", "kernel_type": "script", "is_private": True,
           "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
           "dataset_sources": list(a.datasets),
           "competition_sources": ["rsna-knee-abnormality-detection"], "kernel_sources": []},
          io.open(out / "kernel-metadata.json", "w", encoding="utf-8"), indent=2)

print(f"{out} | stage {a.stage} | pass {a.pass_name} | {a.model} @ {a.rev} | "
      f"quant {a.quant} | batch {a.batch} | shards {a.shards} | max_new {a.max_new}")
if a.rev == "main":
    print("WARNING: revision 'main' is a moving target. Pin a commit sha before the FULL run, "
          "or the extraction is not reproducible from this repo alone.")
if a.dry_run:
    sys.exit(0)
r = subprocess.run(["kaggle", "kernels", "push", "-p", str(out)], capture_output=True, text=True)
print((r.stdout + r.stderr).strip())
sys.exit(r.returncode)
